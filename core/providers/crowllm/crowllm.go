// ImageGeneration performs an Image Generation request to CrowLLM's API.
// It formats the request, sends it to CrowLLM Token Factory, and processes the response.
// Returns a BifrostResponse containing the bifrost response or an error if the request fails.
func (provider *CrowLLMProvider) ImageGeneration(ctx *schemas.BifrostContext, key schemas.Key, request *schemas.BifrostImageGenerationRequest) (*schemas.BifrostImageGenerationResponse, *schemas.BifrostError) {
	// Validate request is not nil
	if request == nil {
		return nil, providerUtils.NewBifrostOperationError("image generation request is nil", nil)
	}

	// Validate input and prompt are not nil/empty
	if request.Input == nil || strings.TrimSpace(request.Input.Prompt) == "" {
		return nil, providerUtils.NewBifrostOperationError("prompt cannot be empty", nil)
	}

	path := providerUtils.GetPathFromContext(ctx, "/v1/images/generations")
	// Create request
	req := fasthttp.AcquireRequest()
	resp := fasthttp.AcquireResponse()
	defer fasthttp.ReleaseRequest(req)
	defer fasthttp.ReleaseResponse(resp)

	// Set any extra headers from network config
	providerUtils.SetExtraHeaders(ctx, req, provider.networkConfig.ExtraHeaders, nil)

	req.SetRequestURI(provider.networkConfig.BaseURL + path)
	req.Header.SetMethod(http.MethodPost)
	req.Header.SetContentType("application/json")

	if value := key.Value.GetValue(); value != "" {
		req.Header.Set("Authorization", "Bearer "+value)
	}

	// Use centralized converter
	jsonData, bifrostErr := providerUtils.CheckContextAndGetRequestBody(
		ctx,
		request,
		func() (*CrowLLMImageGenerationRequest, error) {
			return provider.ToCrowLLMImageGenerationRequest(request)
		})
	if bifrostErr != nil {
		return nil, bifrostErr
	}

	if !providerUtils.ApplyLargePayloadRequestBodyWithModelNormalization(ctx, req, schemas.CrowLLM) {
		req.SetBody(jsonData)
	}

	// Make request
	latency, bifrostErr, wait := providerUtils.MakeRequestWithContext(ctx, provider.client, req, resp)
	defer wait()
	if bifrostErr != nil {
		return nil, bifrostErr
	}

	// Handle error response
	if resp.StatusCode() != fasthttp.StatusOK {
		return nil, providerUtils.EnrichError(ctx, parseCrowLLMImageError(resp), jsonData, nil, providerUtils.ShouldSendBackRawRequest(ctx, provider.sendBackRawRequest), providerUtils.ShouldSendBackRawResponse(ctx, provider.sendBackRawResponse), latency)
	}

	// Time the body read/decompress as the response-finalize phase.
	ft, fh := providerUtils.StartPhaseSpan(ctx, "response-finalize")
	body, err := providerUtils.CheckAndDecodeBody(resp)
	if ft != nil {
		if err != nil {
			ft.EndSpan(fh, schemas.SpanStatusError, err.Error())
		} else {
			ft.EndSpan(fh, schemas.SpanStatusOk, "")
		}
	}
	if err != nil {
		return nil, providerUtils.EnrichError(ctx, providerUtils.NewBifrostOperationError(schemas.ErrProviderResponseDecode, err), jsonData, nil, provider.sendBackRawRequest, provider.sendBackRawResponse, latency)
	}

	response := &schemas.BifrostImageGenerationResponse{}

	sendBackRawRequest, sendBackRawResponse := providerUtils.ShouldSendBackRawRequest(ctx, provider.sendBackRawRequest), providerUtils.ShouldSendBackRawResponse(ctx, provider.sendBackRawResponse)

	// Use enhanced response handler with pre-allocated response
	rawRequest, rawResponse, bifrostErr := providerUtils.HandleProviderResponseCtx(
		ctx,
		body,
		response,
		jsonData,
		sendBackRawRequest,
		sendBackRawResponse,
	)

	if bifrostErr != nil {
		return nil, bifrostErr
	}

	response.ExtraFields.Latency = latency.Milliseconds()

	// Set raw request if enabled
	if sendBackRawRequest {
		response.ExtraFields.RawRequest = rawRequest
	}

	// Set raw response if enabled
	if sendBackRawResponse {
		response.ExtraFields.RawResponse = rawResponse
	}

	return response, nil
}

