// Command genoperations generates the CLI operation catalog from bundled OpenAPI JSON.
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"os"
	"sort"
	"strings"
)

// operation is the catalog representation emitted into Go source.
type operation struct {
	ID         string
	Method     string
	Path       string
	Summary    string
	Tags       []string
	Deprecated bool
}

type openAPIOperation struct {
	OperationID string   `json:"operationId"`
	Summary     string   `json:"summary"`
	Tags        []string `json:"tags"`
	Deprecated  bool     `json:"deprecated"`
}

// openAPIDocument contains the subset of OpenAPI needed for catalog generation.
type openAPIDocument struct {
	Paths map[string]map[string]openAPIOperation `json:"paths"`
}

// exposedSDKBridgeMounts is an explicit product allowlist. Nested SDK bridge
// mounts are omitted from the CLI operation catalog unless the CLI deliberately
// exposes them; raw `bifrost request` remains available for every gateway path.
var exposedSDKBridgeMounts = map[string]struct{}{
	"langchain":  {},
	"pydanticai": {},
}

// main parses the source document and writes deterministic generated Go code.
func main() {
	specPath := flag.String("spec", "", "bundled OpenAPI JSON path")
	outputPath := flag.String("out", "catalog.gen.go", "generated Go output path")
	flag.Parse()
	if strings.TrimSpace(*specPath) == "" {
		fatalf("-spec is required")
	}
	body, err := os.ReadFile(*specPath)
	if err != nil {
		fatalf("read OpenAPI document: %v", err)
	}
	var document openAPIDocument
	if err := json.Unmarshal(body, &document); err != nil {
		fatalf("parse OpenAPI document: %v", err)
	}
	operations, err := collectOperations(document)
	if err != nil {
		fatalf("collect operations: %v", err)
	}
	generated, err := render(operations)
	if err != nil {
		fatalf("render catalog: %v", err)
	}
	if err := os.WriteFile(*outputPath, generated, 0o644); err != nil {
		fatalf("write catalog: %v", err)
	}
}

// collectOperations validates operation IDs and returns a stable sorted list.
func collectOperations(document openAPIDocument) ([]operation, error) {
	allowedMethods := map[string]bool{"get": true, "post": true, "put": true, "patch": true, "delete": true, "head": true, "options": true}
	seen := map[string]struct{}{}
	operations := make([]operation, 0)
	for path, pathItem := range document.Paths {
		for method, source := range pathItem {
			method = strings.ToLower(method)
			if !allowedMethods[method] {
				continue
			}
			if !includeInCatalog(path, source) {
				continue
			}
			if strings.TrimSpace(source.OperationID) == "" {
				return nil, fmt.Errorf("%s %s has no operationId", strings.ToUpper(method), path)
			}
			if _, ok := seen[source.OperationID]; ok {
				return nil, fmt.Errorf("duplicate operationId %q", source.OperationID)
			}
			seen[source.OperationID] = struct{}{}
			operations = append(operations, operation{
				ID: source.OperationID, Method: strings.ToUpper(method), Path: path,
				Summary: source.Summary, Tags: source.Tags, Deprecated: source.Deprecated,
			})
		}
	}
	sort.Slice(operations, func(i, j int) bool { return operations[i].ID < operations[j].ID })
	return operations, nil
}

// includeInCatalog keeps canonical operations and explicitly exposed SDK
// bridge mounts. A nested bridge identifies itself with an integration tag and
// a summary such as "(Bridge - Provider format)".
func includeInCatalog(path string, source openAPIOperation) bool {
	mount := strings.Split(strings.TrimPrefix(path, "/"), "/")[0]
	for _, tag := range source.Tags {
		integration, ok := strings.CutSuffix(tag, " Integration")
		if !ok || !strings.Contains(source.Summary, "("+integration+" - ") {
			continue
		}
		_, exposed := exposedSDKBridgeMounts[strings.ToLower(mount)]
		return exposed
	}
	return true
}

// render emits gofmt-formatted source for the operation catalog.
func render(operations []operation) ([]byte, error) {
	var buffer bytes.Buffer
	buffer.WriteString("// Code generated by go generate; DO NOT EDIT.\n\n")
	buffer.WriteString("package operations\n\n")
	buffer.WriteString("// Catalog contains every operation in the bundled Bifrost OpenAPI document.\n")
	buffer.WriteString("var Catalog = []Operation{\n")
	for _, operation := range operations {
		fmt.Fprintf(&buffer, "{ID: %q, Method: %q, Path: %q, Summary: %q, Tags: %#v, Deprecated: %t},\n",
			operation.ID, operation.Method, operation.Path, operation.Summary, operation.Tags, operation.Deprecated)
	}
	buffer.WriteString("}\n")
	return format.Source(buffer.Bytes())
}

// fatalf prints a generation failure and terminates with a non-zero exit code.
func fatalf(format string, arguments ...any) {
	fmt.Fprintf(os.Stderr, format+"\n", arguments...)
	os.Exit(1)
}
